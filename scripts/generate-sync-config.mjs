import { readFileSync, writeFileSync, existsSync } from "node:fs"
import { join } from "node:path"

const root = process.cwd()
const envPath = join(root, ".env")
const outPath = join(root, "extension/shared/sync-config.js")

function readEnvValue(key) {
  if (!existsSync(envPath)) return ""
  const text = readFileSync(envPath, "utf8")
  for (const line of text.split("\n")) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith("#")) continue
    const idx = trimmed.indexOf("=")
    if (idx === -1) continue
    if (trimmed.slice(0, idx).trim() !== key) continue
    return trimmed.slice(idx + 1).trim().replace(/^["']|["']$/g, "")
  }
  return ""
}

const url = readEnvValue("NEXT_PUBLIC_SUPABASE_URL")
const anonKey = readEnvValue("NEXT_PUBLIC_SUPABASE_ANON_KEY")

const contents = `/**
 * Supabase connection for optional cloud sync.
 * Generated by scripts/generate-sync-config.mjs — do not edit by hand.
 * Run \`npm run sync:config\` to refresh from \`.env\`.
 */
export const SUPABASE_URL = ${JSON.stringify(url)}
export const SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)}

export function isSyncConfigured() {
  return Boolean(SUPABASE_URL && SUPABASE_ANON_KEY)
}
`

writeFileSync(outPath, contents, "utf8")

if (url && anonKey) {
  console.log("Wrote extension/shared/sync-config.js from .env")
} else {
  console.log("Wrote extension/shared/sync-config.js (empty — set Supabase vars in .env)")
}
